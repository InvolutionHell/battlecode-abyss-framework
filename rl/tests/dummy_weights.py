#!/usr/bin/env python3
"""Tiny random weight headers in the exact formats the runtime reads, without torch - for compile / consistency tests.

  python3 rl/tests/dummy_weights.py OUT_DIR [--channels 4 --hidden 8 --seed 0]

Writes into OUT_DIR:
  weights_rl.hpp     a pretrain.py-style float header with auxiliary heads (then export_bot.py makes the int16 files)
  rl_weights.hpp     export_bot.py of it (RL_*)            rla_weights.hpp / rll_weights.hpp   the same with --prefix RLA / RLL
  f1_weights.hpp     an F1 net, no extra inputs, no Q heads (the released move prior's shape)
  f2_weights.hpp     an F2 net: 24 memory inputs and six Q heads (F1_NPRIV 24, F1_HAS_Q / F1_Q_RET / F1_Q_TEAM)
"""
import argparse
import json
import os
import subprocess
import sys

import numpy as np

FC, FS, NA = 17, 10, 16
HERE = os.path.dirname(os.path.abspath(__file__))


def cf(v):
    t = f"{v:.9g}"
    return (t if any(c in t for c in ".eEn") else t + ".0") + "f"


def floats(name, a):
    return f"inline constexpr float {name}[] = {{{','.join(cf(v) for v in np.ravel(a))}}};\n"


def quantised(name, m):
    """train_f1.py's export: int16 values, one float scale per output row"""
    m = m.reshape(m.shape[0], -1).astype(np.float32)
    s = np.abs(m).max(1) / 32767.0
    s[s == 0] = 1e-12
    q = np.clip(np.rint(m / s[:, None]), -32767, 32767).astype(np.int64)
    return (f"inline constexpr int16_t {name}_Q[] = {{{','.join(map(str, q.ravel()))}}};\n"
            f"inline constexpr float {name}_S[] = {{{','.join(cf(v) for v in s)}}};\n")


def layers(rng, c, h, nin_extra, heads):
    """random layers [(name, weight, bias)]: conv1, conv2, dense, then the heads [(name, rows)]"""
    sc = lambda *shape: (rng.standard_normal(shape) * 0.3).astype(np.float32)  # noqa: E731
    out = [("C1", sc(c, FC, 3, 3), sc(c)), ("C2", sc(c, c, 3, 3) * 0.5, sc(c)),
           ("F1", sc(h, c * 49 + FS + 1 + nin_extra) * 0.2, sc(h))]
    out += [(name, sc(rows, h), sc(rows)) for name, rows in heads]
    return out


def write_rl_float(path, rng, c, h, aux=True):
    """the float text header pretrain.py writes (RL_* arrays, not quantised)"""
    with open(path, "w") as f:
        f.write("// GENERATED by rl/tests/dummy_weights.py -- " + json.dumps({"dummy": True, "policy_acc": 0}) + "\n#pragma once\n")
        f.write(f"inline constexpr int RL_NC1 = {c};\ninline constexpr int RL_NH = {h};\n")
        heads = [("POL", 10), ("VAL", 1)] + ([("AUX", 4)] if aux else [])
        if aux:
            f.write("#define RL_HAS_AUX 1\ninline constexpr int RL_NAUX = 4;\n")
        for name, w, b in layers(rng, c, h, 0, heads):
            f.write(floats(f"RL_W_{name}", w) + floats(f"RL_B_{name}", b))


def write_f1(path, rng, c, h, npriv=0, nq=0):
    with open(path, "w") as f:
        f.write("// GENERATED by rl/tests/dummy_weights.py -- " + json.dumps({"dummy": True, "mem": npriv, "q": nq})
                + "\n#pragma once\n#include <cstdint>\nnamespace bc {\n")
        f.write(f"inline constexpr int F1_NC1 = {c};\ninline constexpr int F1_NH = {h};\n"
                f"inline constexpr int F1_NA = {NA};\ninline constexpr int F1_NPRIV = {npriv};\n")
        if nq:
            f.write("#define F1_HAS_Q 1\n" + ("#define F1_Q_RET 1\n" if nq >= 3 else "") + ("#define F1_Q_TEAM 1\n" if nq == 6 else ""))
            wq = (rng.standard_normal((nq * NA, h)) * 0.3).astype(np.float32)
            f.write(quantised("F1_W_Q", wq) + floats("F1_B_Q", (rng.standard_normal(nq * NA) * 0.3).astype(np.float32)))
        for name, w, b in layers(rng, c, h, npriv, [("POL", NA), ("AUX", 5), ("VAL", 3)]):
            f.write(quantised(f"F1_W_{name}", w) + floats(f"F1_B_{name}", b))
        f.write("}  // namespace bc\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("out")
    ap.add_argument("--channels", type=int, default=4)
    ap.add_argument("--hidden", type=int, default=8)
    ap.add_argument("--seed", type=int, default=0)
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    rng = np.random.default_rng(a.seed)
    src = os.path.join(a.out, "weights_rl.hpp")
    write_rl_float(src, rng, a.channels, a.hidden)
    export = os.path.join(HERE, "..", "train", "export_bot.py")
    for name, prefix in (("rl_weights.hpp", []), ("rla_weights.hpp", ["--prefix", "RLA"]), ("rll_weights.hpp", ["--prefix", "RLL"])):
        subprocess.run([sys.executable, export, src, os.path.join(a.out, name)] + prefix, check=True, stdout=subprocess.DEVNULL)
    write_f1(os.path.join(a.out, "f1_weights.hpp"), rng, a.channels, a.hidden)
    write_f1(os.path.join(a.out, "f2_weights.hpp"), rng, a.channels, a.hidden, npriv=24, nq=6)
    print(f"dummy weights in {a.out}")


if __name__ == "__main__":
    main()
