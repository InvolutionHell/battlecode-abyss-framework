#!/usr/bin/env python3
"""Turn pretrain.py's weights_rl.hpp (float text) into a bot's rl_weights.hpp: int16 values with one float scale per
output row, dequantised once per process by rl_net.hpp. About half the source size; on held-out records the argmax
agrees with the float net on more than 99.9% of turns (int8 rows: 98.7%).

  python3 rl/train/export_bot.py RUN_DIR/weights_rl.hpp bots/<bot>/rl_weights.hpp
  python3 rl/train/export_bot.py RUN_DIR/weights_rl.hpp rla_weights.hpp --prefix RLA   # a second net in one bot
          (every RL_ symbol and the RL_HAS_AUX macro become RLA_: rl/runtime/rl_aux.hpp reads them; rl_late.hpp: RLL)

The generated header's first line names the source file by its base name only, plus the training metadata
(sample count, epochs, held-out accuracies); string values in the metadata that look like paths are reduced to base
names too, so no local path ends up in a bot.
"""
import argparse
import json
import os
import re
import sys

ROWS = {"RL_W_C1": "RL_NC1", "RL_W_C2": "RL_NC1", "RL_W_F1": "RL_NH", "RL_W_POL": 10, "RL_W_VAL": 1, "RL_W_AUX": 4}


def scrub(v):
    """a metadata value with every path-like string reduced to its base name"""
    if isinstance(v, str) and ("/" in v or "\\" in v):
        return os.path.basename(v.rstrip("/\\"))
    if isinstance(v, list):
        return [scrub(x) for x in v]
    if isinstance(v, dict):
        return {k: scrub(x) for k, x in v.items()}
    return v


def meta_of(first_line):
    """the JSON metadata after ' -- ' on a generated header's first line ({} if there is none)"""
    _, sep, tail = first_line.partition(" -- ")
    if not sep:
        return {}
    try:
        return scrub(json.loads(tail))
    except json.JSONDecodeError:
        return {}


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("src", help="pretrain.py's weights_rl.hpp")
    ap.add_argument("dst", help="the bot's rl_weights.hpp")
    ap.add_argument("--prefix", default="", help="rename every RL_ symbol to PREFIX_ (a second net in one bot)")
    a = ap.parse_args()
    txt = open(a.src).read()
    meta = meta_of(txt.splitlines()[0])
    consts = {k: int(v) for k, v in re.findall(r"inline constexpr int (\w+) = (\d+);", txt)}
    arrays = {m.group(1): [float(x.rstrip("f")) for x in m.group(2).split(",")]
              for m in re.finditer(r"inline constexpr float (\w+)\[\] = \{([^}]*)\};", txt)}
    if "RL_W_C1" not in arrays:
        sys.exit(f"{a.src}: not a pretrain.py weights file (no RL_W_C1)")
    out = [f"// GENERATED by rl/train/export_bot.py from {os.path.basename(a.src)} -- " + json.dumps(meta),
           "#pragma once", "#include <cstdint>"]
    if "RL_W_AUX" in arrays:  # the auxiliary head (rl_net.hpp computes aux[] when this is defined)
        out.append("#define RL_HAS_AUX 1")
    out.append("namespace bc {")
    out += [f"inline constexpr int {k} = {v};" for k, v in consts.items()]
    for name, vals in arrays.items():
        if name in ROWS:
            rows = ROWS[name] if isinstance(ROWS[name], int) else consts[ROWS[name]]
            per = len(vals) // rows
            scales, q = [], []
            for r in range(rows):
                row = vals[r * per:(r + 1) * per]
                s = max(abs(v) for v in row) / 32767.0 or 1e-12
                scales.append(s)
                q += [max(-32767, min(32767, round(v / s))) for v in row]
            out.append(f"inline constexpr int16_t {name}_Q[] = {{{','.join(map(str, q))}}};")
            out.append(f"inline constexpr float {name}_S[] = {{{','.join(f'{s:.9g}f' for s in scales)}}};")
        else:
            out.append(f"inline constexpr float {name}[] = {{{','.join(f'{v:.9g}f' for v in vals)}}};")
    out.append("}  // namespace bc")
    text = "\n".join(out) + "\n"
    if a.prefix:  # RL_W_C1_Q -> RLA_W_C1_Q, RL_HAS_AUX -> RLA_HAS_AUX, ...
        text = re.sub(r"\bRL_", a.prefix + "_", text)
    os.makedirs(os.path.dirname(os.path.abspath(a.dst)), exist_ok=True)
    open(a.dst, "w").write(text)
    print(f"{a.dst}: {sum(len(v) for v in arrays.values())} weights, policy acc {meta.get('policy_acc', '?')}")


if __name__ == "__main__":
    main()
