#!/usr/bin/env python3
"""Supervised pretraining of the 9-class policy / value net (the released bot's opening prior is this net).

Records: build_rl.py (rl/featurize/featurize_rl.cpp): label, split n, length, steps, outcome bits, round / 2, then the
17 x 7 x 7 grid + 10 scalars quantised x100. Net: conv3x3(17 -> C) relu, conv3x3(C -> C) relu, dense(C*49 + 10 + round
-> H) relu; policy head = the 9 action classes + the split fraction (logit of n / length, trained on split turns);
value head = the game's result (logit). The winners' turns are weighted 1, the losers' --loser-weight (behaviour cloning
weighted by the outcome), or with --awr-beta by exp((result - value) / beta) (advantage-weighted regression). With
--aux-weight > 0 an auxiliary head learns the consequence labels (aux_labels.py) of records that carry them.

  python3 rl/train/pretrain.py "DATA_DIR/rl_*.bin" --out RUN_DIR [--channels 64 --hidden 128 --epochs 12]

Writes RUN_DIR/model.pt (torch state dict), weights_rl.hpp (float text; export_bot.py turns it into the bot's int16
rl_weights.hpp) and train_log.json. Shards may be zstd-compressed (.zst; needs the zstd command).
"""
import argparse
import glob
import json
import os
import subprocess
import sys
import time

import numpy as np
import torch
import torch.nn as nn

FC, FS, NCLASS = 17, 10, 9
FDIM = FC * 49 + FS
HDR = 6
NAUX = 4  # aux_labels.py: split within 5 turns, eat within 5, die within 10 (enemy contact), kill within 10
WCLASS = [1.0, 0.75, 0.5, 0.25]  # a record's sample-weight class, outcome-byte bits 5-6 (build_rl.py: the row's wclass)


class Net(nn.Module):
    def __init__(self, c=64, h=128, aux=False):
        super().__init__()
        self.c1 = nn.Conv2d(FC, c, 3, padding=1)
        self.c2 = nn.Conv2d(c, c, 3, padding=1)
        self.f1 = nn.Linear(c * 49 + FS + 1, h)          # + the round
        self.pol = nn.Linear(h, NCLASS + 1)                # actions + split fraction
        self.val = nn.Linear(h, 1)                         # game result logit
        self.aux = nn.Linear(h, NAUX) if aux else None     # consequence logits (optional)

    def forward(self, x, rnd, with_aux=False):
        g = x[:, : FC * 49].view(-1, FC, 7, 7)
        s = x[:, FC * 49:]
        g = torch.relu(self.c2(torch.relu(self.c1(g))))
        z = torch.relu(self.f1(torch.cat([g.flatten(1), s, rnd], 1)))
        if with_aux:
            return self.pol(z), self.val(z).squeeze(1), self.aux(z)
        return self.pol(z), self.val(z).squeeze(1)


def export(model, path, meta):
    def arr(name, t):
        vals = ",".join(f"{v:.6g}f" for v in t.detach().cpu().numpy().ravel())
        return f"inline constexpr float {name}[] = {{{vals}}};\n"
    with open(path, "w") as f:
        f.write("// GENERATED by rl/train/pretrain.py -- " + json.dumps(meta) + "\n#pragma once\n")
        f.write(f"inline constexpr int RL_NC1 = {model.c1.out_channels};\ninline constexpr int RL_NH = {model.f1.out_features};\n")
        heads = (("RL_W_C1", model.c1.weight), ("RL_B_C1", model.c1.bias), ("RL_W_C2", model.c2.weight),
                 ("RL_B_C2", model.c2.bias), ("RL_W_F1", model.f1.weight), ("RL_B_F1", model.f1.bias),
                 ("RL_W_POL", model.pol.weight), ("RL_B_POL", model.pol.bias), ("RL_W_VAL", model.val.weight),
                 ("RL_B_VAL", model.val.bias))
        if model.aux is not None:
            f.write(f"#define RL_HAS_AUX 1\ninline constexpr int RL_NAUX = {NAUX};\n")
            heads += (("RL_W_AUX", model.aux.weight), ("RL_B_AUX", model.aux.bias))
        for name, t in heads:
            f.write(arr(name, t))


def auc(score, target):
    """Area under the ROC curve (rank statistic); 0.5 when a class is missing."""
    pos = target > 0.5
    npos, nneg = int(pos.sum()), int((~pos).sum())
    if npos == 0 or nneg == 0:
        return 0.5
    ranks = torch.empty_like(score)
    ranks[score.argsort()] = torch.arange(1, len(score) + 1, dtype=score.dtype)
    return float((ranks[pos].sum() - npos * (npos + 1) / 2) / (npos * nneg))


def read_shard(path):
    """A shard of build_rl.py records, raw or zstd-compressed (.zst: about a tenth of the size)."""
    if path.endswith(".zst"):
        buf = subprocess.run(["zstd", "-dc", "-q", path], capture_output=True, check=True).stdout
        return np.frombuffer(buf, dtype=np.uint8).reshape(-1, HDR + FDIM)
    return np.fromfile(path, dtype=np.uint8).reshape(-1, HDR + FDIM)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("samples", nargs="+")
    ap.add_argument("--out", required=True)
    ap.add_argument("--epochs", type=int, default=12)
    ap.add_argument("--batch", type=int, default=4096)
    ap.add_argument("--channels", type=int, default=64)
    ap.add_argument("--hidden", type=int, default=128)
    ap.add_argument("--loser-weight", type=float, default=0.3, help="policy weight of the losing side's turns")
    ap.add_argument("--value-weight", type=float, default=0.5)
    ap.add_argument("--hours", type=float, default=8.0, help="stop training after this long")
    ap.add_argument("--min-samples", type=int, default=10000)
    ap.add_argument("--init", default="", help="start from this model.pt (fine-tuning)")
    ap.add_argument("--lr", type=float, default=2e-3)
    ap.add_argument("--awr-beta", type=float, default=0.0,
                    help="weight each turn's policy loss by exp((result - value) / beta), capped at "
                         "--awr-max (advantage-weighted regression; 0: the winner / loser weights instead)")
    ap.add_argument("--awr-max", type=float, default=20.0)
    ap.add_argument("--aux-weight", type=float, default=0.0,
                    help="train the auxiliary consequence head on records that carry its labels (outcome bit 7)")
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)
    dev = "cuda" if torch.cuda.is_available() else "cpu"
    if dev == "cuda":
        try:  # a wheel built without this GPU's architecture only fails at the first kernel
            (torch.ones(8, device=dev) * 2).sum().item()
        except RuntimeError as e:
            print(f"cuda unusable ({e}); training on the CPU", flush=True)
            dev = "cpu"
    print(f"device {dev} {torch.cuda.get_device_name(0) if dev == 'cuda' else ''} torch {torch.__version__}", flush=True)
    files = sorted(set(p for s in args.samples for p in glob.glob(s)))
    raw = np.concatenate([read_shard(p) for p in files])
    n = len(raw)
    if n < args.min_samples:
        sys.exit(f"only {n} samples in {len(files)} files")
    has_aux = (raw[:, 4] >> 7).astype(bool)
    print(f"{n} samples from {len(files)} shards on {dev}; classes {np.bincount(raw[:, 0], minlength=NCLASS).tolist()}; "
          f"winners' turns {(raw[:, 4] & 1).mean():.2f}; with consequence labels {has_aux.mean():.2f}"
          + (f" (rates {[round(float(((raw[has_aux, 4] >> (k + 1)) & 1).mean()), 3) for k in range(NAUX)]})"
             if has_aux.any() else ""), flush=True)
    rng = np.random.default_rng(0)
    idx = rng.permutation(n)
    val, tr = idx[: n // 20], idx[n // 20:]
    x = torch.from_numpy(raw[:, HDR:].astype(np.float32) / 100.0)
    rnd = torch.from_numpy((raw[:, 5].astype(np.float32) * 2 / 500.0)).unsqueeze(1)
    y = torch.from_numpy(raw[:, 0].astype(np.int64))
    won = torch.from_numpy((raw[:, 4] & 1).astype(np.float32))
    auxy = torch.from_numpy(np.stack([(raw[:, 4] >> (k + 1)) & 1 for k in range(NAUX)], 1).astype(np.float32))
    auxm = torch.from_numpy(has_aux.astype(np.float32))
    use_aux = args.aux_weight > 0 and bool(has_aux.any())
    sw = torch.from_numpy(np.array(WCLASS, dtype=np.float32)[(raw[:, 4] >> 5) & 3])
    if (sw < 1).any():
        print(f"sample-weight classes: {np.bincount((raw[:, 4] >> 5) & 3, minlength=4).tolist()}", flush=True)
    frac = torch.from_numpy((raw[:, 1] / np.maximum(raw[:, 2], 1)).astype(np.float32))
    model = Net(args.channels, args.hidden, aux=use_aux).to(dev)
    if args.init:
        missing, _ = model.load_state_dict(torch.load(args.init, map_location=dev), strict=False)
        print(f"initialised from {args.init}" + (f" (new: {missing})" if missing else ""), flush=True)
    opt = torch.optim.AdamW(model.parameters(), lr=args.lr, weight_decay=1e-4)
    sched = torch.optim.lr_scheduler.CosineAnnealingLR(opt, T_max=args.epochs)
    ce = nn.CrossEntropyLoss(reduction="none")
    bce = nn.BCEWithLogitsLoss()
    stop = time.time() + args.hours * 3600
    log = []
    for ep in range(args.epochs):
        model.train()
        perm = torch.from_numpy(rng.permutation(tr))
        for i in range(0, len(perm), args.batch):
            b = perm[i:i + args.batch]
            xb, rb, yb, wb = x[b].to(dev), rnd[b].to(dev), y[b].to(dev), won[b].to(dev)
            if use_aux:
                pol, v, ax = model(xb, rb, with_aux=True)
            else:
                pol, v = model(xb, rb)
            if args.awr_beta > 0:  # moves that did better than the value expected count more
                wts = torch.exp((wb - torch.sigmoid(v.detach())) / args.awr_beta).clamp(max=args.awr_max)
            else:
                wts = torch.where(wb > 0.5, torch.ones_like(wb), torch.full_like(wb, args.loser_weight))
            wts = wts * sw[b].to(dev)
            loss = (ce(pol[:, :NCLASS], yb) * wts).sum() / wts.sum() + args.value_weight * bce(v, wb)
            sp = yb == 8
            if sp.any():
                loss = loss + 0.5 * bce(pol[sp, NCLASS], frac[b].to(dev)[sp])
            if use_aux:
                m = auxm[b].to(dev)
                if m.sum() > 0:
                    la = nn.functional.binary_cross_entropy_with_logits(ax, auxy[b].to(dev), reduction="none").mean(1)
                    loss = loss + args.aux_weight * (la * m).sum() / m.sum()
            opt.zero_grad()
            loss.backward()
            opt.step()
        sched.step()
        model.eval()
        with torch.no_grad():
            vb = torch.from_numpy(val)
            out = model(x[vb].to(dev), rnd[vb].to(dev), with_aux=use_aux)
            pol, v = out[0], out[1]
            acc = (pol[:, :NCLASS].argmax(1).cpu() == y[vb]).float().mean().item()
            vacc = ((v.cpu() > 0).float() == won[vb]).float().mean().item()
        log.append({"epoch": ep + 1, "loss": round(loss.item(), 4), "policy_acc": round(acc, 4), "value_acc": round(vacc, 4)})
        if use_aux:  # per label: the ranking quality (AUC) on held-out records that carry labels
            mv = auxm[vb].bool()
            p, t = torch.sigmoid(out[2].cpu()[mv]), auxy[vb][mv]
            log[-1]["aux_auc"] = [round(auc(p[:, k], t[:, k]), 3) for k in range(NAUX)]
        print(json.dumps(log[-1]), flush=True)
        torch.save(model.state_dict(), os.path.join(args.out, "model.pt"))
        if time.time() > stop:
            break
    meta = {"samples": int(n), "shards": len(files), "epochs": len(log), **log[-1]}
    export(model, os.path.join(args.out, "weights_rl.hpp"), meta)
    json.dump({"meta": meta, "log": log}, open(os.path.join(args.out, "train_log.json"), "w"), indent=1)
    print("done", json.dumps(meta), flush=True)


if __name__ == "__main__":
    main()
